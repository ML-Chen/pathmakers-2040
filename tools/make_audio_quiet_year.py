"""Record the Lantern Garden's spoken lines into src/viz/quiet_year_audio.js (merged into AUDIO at load).

Reuses tools/make_audio.py (same Kokoro model, cache, voices and post-processing); only the line
list and the output file differ, so this mission never edits the shared src/audio.js.
  python3 tools/make_audio_quiet_year.py
"""
import json, os, subprocess, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import make_audio as MA

MA.OUT_JS = os.path.join(MA.REPO, "src", "viz", "quiet_year_audio.js")
# Tomas, the garden keeper: a warm, slower older voice.
MA.ROLES["am_onyx"] = dict(speaker="am_onyx", speed=0.96, pitch=0.96, formant=1.0)
MA.PRONOUNCE.append((r"\bVarrow\b", "Varrow"))
MA.PRONOUNCE.append((r"\bLucía\b", "Lucia"))

NODE = ("const fs=require('fs'),vm=require('vm');const c={module:{exports:{}}};vm.createContext(c);"
        "vm.runInContext(['src/art.js','src/content_boston.js','src/missions.js','src/missions/quiet_year.js']"
        ".map(f=>fs.readFileSync(f,'utf8')).join('\\n')+';this.L=qySpokenLines();',c);process.stdout.write(JSON.stringify(c.L))")

def load_lines():
    out = subprocess.run(["node", "-e", NODE], cwd=MA.REPO, check=True, capture_output=True, text=True).stdout
    seen, lines = set(), []
    for item in json.loads(out):
        key = item["voice"] + "|" + item["text"]
        if key not in seen:
            seen.add(key)
            lines.append((item["voice"], item["text"]))
    return lines

MA.load_lines = load_lines

if __name__ == "__main__":
    MA.main()
    js = open(MA.OUT_JS, encoding="ascii").read()
    js = js.replace("const AUDIO={\n", "Object.assign(AUDIO,{\n", 1).replace(
        "\n};\nif(typeof window!=='undefined')window.AUDIO=AUDIO;\n", "\n});\n")
    js = js.replace("// Generated by tools/make_audio.py", "// Generated by tools/make_audio_quiet_year.py")
    open(MA.OUT_JS, "w", encoding="ascii").write(js)
