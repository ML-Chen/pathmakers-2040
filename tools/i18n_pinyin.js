// Generate pinyin for Chinese mode: node tools/i18n_pinyin.js [lang=zh]
// Needs pinyin-pro (npm install pinyin-pro). Run by .github/workflows/pinyin.yml on GitHub's machines.
// For every translation file src/i18n/<lang>/<id>.js it writes src/i18n/<lang>_pinyin/<id>.js, which calls
// I18N.pyText(id, corpus, syllables): the corpus is every Chinese string of that file (translations, glossary terms,
// definitions and alt forms), as the player sees it, joined with newlines; syllables lists one tone-marked pinyin per
// Chinese character of the corpus, read sentence by sentence so polyphonic characters (行, 长, 还…) keep the reading
// of their sentence. It also writes _chars.js: I18N.pyChars() with the common reading of every GB2312 character, so
// text that is not in any file (the player's name, Byte's live chat replies) still gets pinyin.
const fs = require('fs'), path = require('path');
const {pinyin} = require('pinyin-pro');
const LG = process.argv[2] || 'zh';
const ROOT = path.resolve(__dirname, '..'), SRC = path.join(ROOT, 'src', 'i18n', LG), OUT = path.join(ROOT, 'src', 'i18n', LG + '_pinyin');
const HAN = /[㐀-鿿豈-﫿]/;   // the same test as I18N_HAN in src/i18n.js

// What the player sees: no [[glossary]] brackets, no HTML tags, no {placeholders}.
const visible = s => String(s).replace(/<[^>]*>/g, ' ').replace(/\[\[([^\]|]*)(?:\|[^\]]*)?\]\]/g, '$1').replace(/\{\w+\}/g, ' ');
// One syllable per Han character of s, in order ('' when pinyin-pro has no reading).
function syllables(s) {
  const out = [];
  for (const it of pinyin(s, {type: 'all', toneType: 'symbol'})) {
    for (const ch of it.origin) if (HAN.test(ch)) out.push(it.isZh && it.pinyin ? it.pinyin.replace(/\s+/g, '') : '');
  }
  return out;
}

// Load every translation file with a stub I18N that records what each one adds.
const files = {};
global.window = global;
global.I18N = {add(lang, id, d) { if (lang === LG) files[id] = d; }};
for (const f of fs.readdirSync(SRC).filter(f => f.endsWith('.js')).sort()) require(path.join(SRC, f));

fs.mkdirSync(OUT, {recursive: true});
for (const f of fs.readdirSync(OUT)) if (f.endsWith('.js')) fs.unlinkSync(path.join(OUT, f));
let total = 0;
const seen = new Set();
for (const id of Object.keys(files).sort()) {
  const d = files[id], texts = [];
  for (const v of Object.values(d.strings || {})) texts.push(v);
  for (const g of Object.values(d.glossary || {})) { if (g.w) texts.push(g.w); if (g.d) texts.push(g.d); for (const a of g.alt || []) texts.push(a); }
  const lines = [], syl = [];
  for (const t of texts) {
    const v = visible(t).replace(/\s*\n\s*/g, ' ').trim();
    if (!v || !HAN.test(v) || seen.has(v)) continue;
    seen.add(v);
    lines.push(v); syl.push(...syllables(v));
  }
  if (!lines.length) continue;
  const corpus = lines.join('\n');
  const nHan = [...corpus].filter(ch => HAN.test(ch)).length;
  if (nHan !== syl.length) throw new Error(`${id}: ${nHan} Chinese characters but ${syl.length} syllables`);
  fs.writeFileSync(path.join(OUT, id + '.js'),
    `// Generated by tools/i18n_pinyin.js from src/i18n/${LG}/${id}.js. Do not edit by hand.\n` +
    `I18N.pyText(${JSON.stringify(id)},${JSON.stringify(corpus)},${JSON.stringify(syl.join(' '))});\n`);
  total += syl.length;
  console.log(`${id}: ${lines.length} strings, ${syl.length} characters`);
}

// Common readings of every GB2312 character (6,763 of them), for text outside the translation files.
const dec = new TextDecoder('gb18030'), chars = [];
for (let a = 0xB0; a <= 0xF7; a++) for (let b = 0xA1; b <= 0xFE; b++) {
  const ch = dec.decode(Uint8Array.from([a, b]));
  if (ch.length === 1 && HAN.test(ch)) chars.push(ch);
}
const cs = chars.map(ch => (pinyin(ch, {toneType: 'symbol'}) || '').replace(/\s+/g, ''));
fs.writeFileSync(path.join(OUT, '_chars.js'),
  `// Generated by tools/i18n_pinyin.js: the common reading of each GB2312 character. Do not edit by hand.\n` +
  `I18N.pyChars(${JSON.stringify(chars.join(''))},${JSON.stringify(cs.join(' '))});\n`);
console.log(`${Object.keys(files).length} files, ${total} characters in context, ${chars.length} single characters`);
