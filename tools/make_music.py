#!/usr/bin/env python3
"""Encode the background music tracks into src/music_tracks.js.
The tracks are rendered by music-lab (github.com/ML-Chen/oct-2026-dump, folder music-lab).
Usage: python3 tools/make_music.py /path/to/oct-2026-dump/music-lab"""
import base64, json, os, subprocess, sys, tempfile
LAB = sys.argv[1] if len(sys.argv) > 1 else '/home/claude/oct-2026-dump/music-lab'
TRACKS = {  # scene -> music-lab demo
    'title': 'demos/retro/lanternbrook_v2.mp3',        # Super Nintendo town theme
    'morning': 'demos/band/late_tram_v2.mp3',          # jazz piano trio
    'hospital': 'demos/band/lantern_hours_v3.mp3',     # solo piano
    'work': 'demos/band/rain_fire_escape_v3.mp3',      # lo-fi hip hop
    'table': 'demos/edm/synthwave/neon_causeway_v3.mp3',  # synthwave
    'win': 'demos/game/hilltop_dash_v2.mp3',           # NES chiptune
    'night': 'demos/world/river_lamps_v4.mp3',         # Chinese traditional
}
out = {}
with tempfile.TemporaryDirectory() as tmp:
    for k, f in TRACKS.items():
        o = os.path.join(tmp, k + '.ogg')
        subprocess.run(['ffmpeg', '-y', '-v', 'error', '-i', os.path.join(LAB, f), '-af', 'loudnorm=I=-20:TP=-2:LRA=11,afade=t=in:d=0.6',
                        '-c:a', 'libopus', '-b:a', '40k', '-ar', '48000', '-ac', '2', o], check=True)
        out[k] = 'data:audio/ogg;base64,' + base64.b64encode(open(o, 'rb').read()).decode()
dst = os.path.join(os.path.dirname(__file__), '..', 'src', 'music_tracks.js')
open(dst, 'w').write('// music_tracks.js — background music rendered with ML-Chen/oct-2026-dump music-lab (Ogg Opus, 40 kbps). Generated by tools/make_music.py.\nconst MUSIC_TRACKS=' + json.dumps(out) + ';\n')
print('wrote', dst, sum(len(v) for v in out.values()) // 1024, 'KB')
